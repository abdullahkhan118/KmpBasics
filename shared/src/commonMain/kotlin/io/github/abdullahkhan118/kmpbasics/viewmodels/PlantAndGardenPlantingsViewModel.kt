package io.github.abdullahkhan118.kmpbasics.viewmodels

import io.github.abdullahkhan118.kmpbasics.data.PlantAndGardenPlantings

class PlantAndGardenPlantingsViewModel(plantings: PlantAndGardenPlantings) {
    private val plant = checkNotNull(plantings.plant)
    private val gardenPlanting = plantings.gardenPlantings[0]

    val waterDateString: String = gardenPlanting.lastWateringDate.toString()
    val wateringInterval
        get() = plant.wateringInterval
    val imageUrl
        get() = plant.imageUrl
    val plantName
        get() = plant.name
    val plantDateString: String = gardenPlanting.plantDate.toString()
    val plantId
        get() = plant.plantId

}